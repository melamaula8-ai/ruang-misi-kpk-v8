/**
 * Logika backend Ruang Misi KPK yang tidak bergantung pada platform.
 * Dipakai oleh Cloudflare Pages Functions (functions/api/*.ts) dan oleh tes lokal
 * (tests/sync.test.ts) yang memakai SQLite sungguhan lewat adaptor D1.
 *
 * Semua penulisan dikirim lewat db.batch() sehingga atomik, dan setiap pelanggaran
 * aturan (ID sudah dipakai, sesi sudah dihapus guru) dijaga di dalam SQL, bukan hanya
 * di JavaScript, supaya dua perangkat yang menulis bersamaan tidak saling menimpa.
 */

export interface D1Result { results?: any[]; meta?: { changes?: number } }
export interface D1Stmt {
  bind(...values: unknown[]): D1Stmt;
  all<T = any>(): Promise<{ results: T[] }>;
  first<T = any>(): Promise<T | null>;
  run(): Promise<D1Result>;
}
export interface D1Like {
  prepare(sql: string): D1Stmt;
  batch(statements: D1Stmt[]): Promise<D1Result[]>;
}
export interface Env {
  DB: D1Like;
  TEACHER_USERNAME?: string;
  /** PBKDF2-SHA256 hash generated by scripts/hash-password.mjs; never store plaintext here. */
  TEACHER_PASSWORD_HASH?: string;
  /** Compatibility for local/legacy setup only; prefer TEACHER_PASSWORD_HASH in production. */
  TEACHER_PASSWORD?: string;
  TEACHER_SESSION_SECRET?: string;
  GOOGLE_CLIENT_ID?: string;
}

// ---------------------------------------------------------------- util umum
const encoder = new TextEncoder();
const SESSION_TTL_MS = 8 * 60 * 60 * 1000;

const json = (body: unknown, status = 200) =>
  new Response(JSON.stringify(body), {
    status,
    headers: { 'Content-Type': 'application/json; charset=utf-8', 'Cache-Control': 'no-store' },
  });

class SyncError extends Error {
  constructor(public code: string, message: string, public status: number) { super(message); }
}

function toBase64Url(bytes: Uint8Array): string {
  let binary = '';
  for (const b of bytes) binary += String.fromCharCode(b);
  return btoa(binary).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
}
function fromBase64Url(text: string): Uint8Array {
  const padded = text.replace(/-/g, '+').replace(/_/g, '/') + '='.repeat((4 - (text.length % 4)) % 4);
  const binary = atob(padded);
  return Uint8Array.from(binary, (c) => c.charCodeAt(0));
}
/** Perbandingan waktu-tetap agar kata sandi/tanda tangan tidak bocor lewat waktu respons. */
function safeEqual(a: string, b: string): boolean {
  const x = encoder.encode(a), y = encoder.encode(b);
  let diff = x.length ^ y.length;
  const len = Math.max(x.length, y.length);
  for (let i = 0; i < len; i++) diff |= (x[i] ?? 0) ^ (y[i] ?? 0);
  return diff === 0;
}
async function hmac(secret: string, payload: string): Promise<string> {
  const key = await crypto.subtle.importKey('raw', encoder.encode(secret), { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']);
  return toBase64Url(new Uint8Array(await crypto.subtle.sign('HMAC', key, encoder.encode(payload))));
}
export async function issueTeacherToken(env: Env, username: string): Promise<string> {
  const payload = toBase64Url(encoder.encode(JSON.stringify({ sub: username, exp: Date.now() + SESSION_TTL_MS })));
  return `${payload}.${await hmac(env.TEACHER_SESSION_SECRET || '', payload)}`;
}
export async function getTeacherIdentity(env: Env, request: Request): Promise<string | null> {
  const authorization = request.headers.get('authorization') || '';
  const secret = env.TEACHER_SESSION_SECRET || '';
  if (!authorization.startsWith('Bearer ') || !secret) return null;
  const [payload, signature] = authorization.slice(7).trim().split('.');
  if (!payload || !signature) return null;
  if (!safeEqual(signature, await hmac(secret, payload))) return null;
  try {
    const decoded = JSON.parse(new TextDecoder().decode(fromBase64Url(payload)));
    return typeof decoded.sub === 'string' && decoded.sub.length > 0 && decoded.exp > Date.now() ? decoded.sub : null;
  } catch { return null; }
}
async function verifyTeacherToken(env: Env, request: Request): Promise<boolean> {
  return Boolean(await getTeacherIdentity(env, request));
}

// ---------------------------------------------------------------- autentikasi guru
const PASSWORD_HASH_PREFIX = 'pbkdf2-sha256';
const MIN_PASSWORD_ITERATIONS = 100_000;
const MAX_PASSWORD_ITERATIONS = 600_000;

async function verifyPasswordHash(password: string, encoded: string): Promise<boolean> {
  try {
    const [algorithm, iterationText, saltText, digestText] = encoded.split('$');
    const iterations = Number(iterationText);
    if (algorithm !== PASSWORD_HASH_PREFIX || !Number.isInteger(iterations) ||
        iterations < MIN_PASSWORD_ITERATIONS || iterations > MAX_PASSWORD_ITERATIONS || !saltText || !digestText) return false;
    const key = await crypto.subtle.importKey('raw', encoder.encode(password), 'PBKDF2', false, ['deriveBits']);
    const bits = await crypto.subtle.deriveBits({ name: 'PBKDF2', hash: 'SHA-256', salt: fromBase64Url(saltText), iterations }, key, 256);
    return safeEqual(toBase64Url(new Uint8Array(bits)), digestText);
  } catch { return false; }
}

export async function handleTeacherAuth(request: Request, env: Env): Promise<Response> {
  if (request.method !== 'POST') return json({ error: 'Method not allowed' }, 405);
  const userExpected = (env.TEACHER_USERNAME || '').trim();
  const passwordHash = env.TEACHER_PASSWORD_HASH || '';
  const legacyPassword = env.TEACHER_PASSWORD || '';
  if (!userExpected || (!passwordHash && !legacyPassword) || !env.TEACHER_SESSION_SECRET) {
    return json({ error: 'Login guru belum dikonfigurasi. Atur TEACHER_USERNAME, TEACHER_PASSWORD_HASH (disarankan), dan TEACHER_SESSION_SECRET.' }, 503);
  }
  let body: { username?: unknown; password?: unknown };
  try { body = await request.json(); } catch { return json({ error: 'Invalid JSON' }, 400); }
  if (typeof body.username !== 'string' || typeof body.password !== 'string') {
    return json({ error: 'Username dan kata sandi wajib diisi.' }, 400);
  }
  const passwordValid = passwordHash
    ? await verifyPasswordHash(body.password, passwordHash)
    : Boolean(legacyPassword) && safeEqual(body.password, legacyPassword);
  if (!safeEqual(body.username.trim(), userExpected) || !passwordValid) {
    return json({ error: 'Username atau kata sandi tidak sesuai.' }, 401);
  }
  return json({ token: await issueTeacherToken(env, userExpected), expiresIn: SESSION_TTL_MS / 1000 });
}

// ---------------------------------------------------------------- kelas dan undangan
const CODE_CHARS = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
function randomCode(length: number): string {
  const bytes = crypto.getRandomValues(new Uint8Array(length));
  return Array.from(bytes, (byte) => CODE_CHARS[byte % CODE_CHARS.length]).join('');
}

export async function handleClasses(request: Request, env: Env): Promise<Response> {
  if (!env.DB) return json({ error: 'Database belum tersedia.' }, 503);
  const hasBearer = (request.headers.get('authorization') || '').startsWith('Bearer ');
  const teacherIdentity = await getTeacherIdentity(env, request);
  const teacher = Boolean(teacherIdentity);
  if (hasBearer && !teacher) return json({ error: 'Sesi guru tidak valid atau sudah kedaluwarsa.' }, 401);

  if (request.method === 'GET') {
    if (teacherIdentity) {
      const rows = await env.DB.prepare(
        'SELECT id, name, join_code AS joinCode, status, created_at AS createdAt FROM classes WHERE teacher_username = ? ORDER BY created_at DESC'
      ).bind(teacherIdentity).all();
      return json({ classes: rows.results });
    }
    const url = new URL(request.url);
    const code = upper(url.searchParams.get('code'));
    if (!code) return json({ error: 'Masukkan kode kelas.' }, 400);
    const row = await env.DB.prepare(
      "SELECT id, name, join_code AS joinCode, status FROM classes WHERE join_code = ? AND status = 'active'"
    ).bind(code).first<any>();
    if (!row) return json({ error: 'Kode kelas tidak ditemukan atau kelas sudah ditutup.' }, 404);
    return json({ class: row });
  }

  if (request.method !== 'POST') return json({ error: 'Method not allowed' }, 405);
  if (!teacher) return json({ error: 'Hanya guru yang masuk yang dapat membuat kelas.' }, 401);
  let body: any;
  try { body = await request.json(); } catch { return json({ error: 'Invalid JSON' }, 400); }
  const name = typeof body?.name === 'string' ? body.name.trim().slice(0, 80) : '';
  if (name.length < 3) return json({ error: 'Nama kelas minimal 3 karakter.' }, 400);

  for (let attempt = 0; attempt < 5; attempt++) {
    const id = crypto.randomUUID();
    const joinCode = `KELAS-${randomCode(6)}`;
    const createdAt = Date.now();
    try {
      await env.DB.prepare(
        'INSERT INTO classes (id, teacher_username, name, join_code, status, created_at) VALUES (?, ?, ?, ?, \'active\', ?)'
      ).bind(id, teacherIdentity, name, joinCode, createdAt).run();
      return json({ class: { id, name, joinCode, status: 'active', createdAt } }, 201);
    } catch (error) {
      if (/UNIQUE/i.test(String(error))) continue;
      console.error('[classes] Gagal membuat kelas:', error);
      return json({ error: 'Kelas gagal disimpan.' }, 500);
    }
  }
  return json({ error: 'Kode kelas unik belum berhasil dibuat. Coba kembali.' }, 503);
}

export async function handleGroupToken(request: Request, env: Env): Promise<Response> {
  if (request.method !== 'POST') return json({ error: 'Method not allowed' }, 405);
  if (!env.DB) return json({ error: 'Database belum tersedia.' }, 503);
  const hasBearer = (request.headers.get('authorization') || '').startsWith('Bearer ');
  const teacherIdentity = await getTeacherIdentity(env, request);
  if (hasBearer && !teacherIdentity) return json({ error: 'Sesi guru tidak valid atau sudah kedaluwarsa.' }, 401);
  let body: any;
  try { body = await request.json(); } catch { return json({ error: 'Invalid JSON' }, 400); }

  // ID yang dibuat guru selalu diikat ke akun pemilik dan satu record kelas di D1.
  // Ini membuat sesi siswa tersimpan pada owner_id yang sama dengan dashboard guru.
  if (teacherIdentity) {
    const quantity = Math.max(1, Math.min(50, Number.isInteger(body?.quantity) ? body.quantity : 1));
    const prefix = (typeof body?.prefix === 'string' ? body.prefix : 'KPK').toUpperCase().replace(/[^A-Z0-9]/g, '').slice(0, 8) || 'KPK';
    const accountTag = teacherIdentity.toUpperCase().replace(/[^A-Z0-9]/g, '').slice(0, 12) || 'GURU';
    const requestedName = typeof body?.className === 'string' ? body.className.trim().slice(0, 80) : '';
    const className = requestedName || `Kelas ${teacherIdentity}`;
    for (let attempt = 0; attempt < 5; attempt += 1) {
      const classId = crypto.randomUUID();
      const classCode = `KELAS-${randomCode(6)}`;
      const now = Date.now();
      const tokens: any[] = Array.from({ length: quantity }, () => {
        const code = `${prefix}-${accountTag}-${randomCode(6)}`;
        return {
          id: crypto.randomUUID(), code, status: 'available',
          createdAt: new Date(now).toISOString(), classId, className, classCode,
        };
      });
      try {
        const statements = [env.DB.prepare(
          "INSERT INTO classes (id, teacher_username, name, join_code, status, group_count, created_at) VALUES (?, ?, ?, ?, 'active', ?, ?)"
        ).bind(classId, teacherIdentity, className, classCode, quantity, now)];
        for (const token of tokens) statements.push(env.DB.prepare(
          "INSERT INTO group_tokens (id, code, status, claimed_by, data, updated_at, owner_id) VALUES (?, ?, 'available', NULL, ?, ?, ?)"
        ).bind(token.id, token.code, JSON.stringify(token), now, teacherIdentity));
        await env.DB.batch(statements);
        return json({ success: true, tokens, class: { id: classId, name: className, joinCode: classCode } }, 201);
      } catch (error) {
        if (/UNIQUE/i.test(String(error))) continue;
        console.error('[group-token] Gagal membuat ID kelas guru:', error);
        return json({ error: 'ID kelas gagal disimpan ke akun guru.' }, 500);
      }
    }
    return json({ error: 'Belum berhasil membuat ID kelas yang unik. Coba kembali.' }, 503);
  }

  const classCode = upper(body?.classCode);
  if (!classCode) return json({ error: 'Masukkan kode kelas dari guru.' }, 400);
  try {
    const classroom = await env.DB.prepare(
      "SELECT id, name, join_code, teacher_username FROM classes WHERE join_code = ? AND status = 'active'"
    ).bind(classCode).first<any>();
    if (!classroom) return json({ error: 'Kode kelas tidak ditemukan atau kelas sudah ditutup.' }, 404);

    for (let attempt = 0; attempt < 5; attempt++) {
      const code = `KPK-${randomCode(3)}-${randomCode(3)}`;
      const id = crypto.randomUUID();
      const now = Date.now();
      const token = { id, code, status: 'available', createdAt: new Date(now).toISOString(), classId: classroom.id, className: classroom.name, classCode: classroom.join_code };
      const reserved = await env.DB.prepare(
        "UPDATE classes SET group_count = group_count + 1 WHERE id = ? AND status = 'active' AND group_count < 50"
      ).bind(classroom.id).run();
      if (!reserved.meta?.changes) return json({ error: 'Kelas ini sudah mencapai batas 50 kelompok atau sudah ditutup. Hubungi guru.' }, 429);
      try {
        await env.DB.prepare(
          `INSERT INTO group_tokens (id, code, status, claimed_by, data, updated_at, owner_id) VALUES (?, ?, 'available', NULL, ?, ?, ?)`
        ).bind(id, code, JSON.stringify(token), now, classroom.teacher_username || 'legacy').run();
        return json({ success: true, token, class: { id: classroom.id, name: classroom.name, joinCode: classroom.join_code } }, 201);
      } catch (error) {
        await env.DB.prepare('UPDATE classes SET group_count = CASE WHEN group_count > 0 THEN group_count - 1 ELSE 0 END WHERE id = ?').bind(classroom.id).run();
        if (/UNIQUE/i.test(String(error))) continue;
        throw error;
      }
    }
    return json({ error: 'Belum berhasil membuat sesi kelompok. Silakan coba kembali.' }, 503);
  } catch (error) {
    console.error('[group-token] Gagal membuat sesi kelompok:', error);
    return json({ error: 'Sesi kelompok gagal disimpan ke database.' }, 500);
  }
}

