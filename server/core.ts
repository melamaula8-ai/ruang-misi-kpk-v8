type Row = { id: string; [key: string]: unknown };
const SETTINGS_KEYS = new Set(['questions', 'trackLock', 'rubric', 'customLogo', 'learningContent']);
const PUBLIC_SETTINGS = ['questions', 'trackLock', 'customLogo', 'learningContent'];
const STUDENT_STATUSES = new Set(['in_progress', 'submitted_pending_review', 'time_expired_pending_review']);
const MAX_ROWS_PER_REQUEST = 500;

const isRows = (v: unknown): v is Row[] =>
  Array.isArray(v) && v.length <= MAX_ROWS_PER_REQUEST && v.every((r) => r && typeof r === 'object' && typeof (r as Row).id === 'string' && (r as Row).id.length > 0 && (r as Row).id.length <= 120);
const isIds = (v: unknown): v is string[] =>
  Array.isArray(v) && v.length <= MAX_ROWS_PER_REQUEST && v.every((id) => typeof id === 'string' && id.length > 0 && id.length <= 120);
const parse = (text: string) => { try { return JSON.parse(text); } catch { return null; } };
const upper = (v: unknown) => (typeof v === 'string' ? v.trim().toUpperCase() : '');

const SQL = {
  upsertToken: `INSERT INTO group_tokens (id, code, status, claimed_by, data, updated_at, owner_id) VALUES (?, ?, ?, ?, ?, ?, ?)
    ON CONFLICT(id) DO UPDATE SET code = excluded.code, status = excluded.status, claimed_by = excluded.claimed_by, data = excluded.data, updated_at = excluded.updated_at WHERE group_tokens.owner_id = excluded.owner_id`,
  upsertSubmissionTeacher: `INSERT INTO submissions (id, group_code, data, updated_at, owner_id) VALUES (?, ?, ?, ?, ?)
    ON CONFLICT(id) DO UPDATE SET group_code = excluded.group_code, data = excluded.data, updated_at = excluded.updated_at WHERE submissions.owner_id = excluded.owner_id`,
  tombstone: `INSERT OR IGNORE INTO revoked_sessions (submission_id, group_code, revoked_at)
    VALUES (?, COALESCE((SELECT group_code FROM submissions WHERE id = ?), ?), ?)`,
  // Siswa hanya boleh menyimpan sesi yang (a) belum dihapus guru dan (b) memegang ID kelompoknya.
  upsertSubmissionStudent: `INSERT INTO submissions (id, group_code, data, updated_at, owner_id)
    SELECT ?1, ?2, ?3, ?4, owner_id FROM group_tokens
      WHERE code = ?2 AND status = 'claimed' AND json_extract(?3, '$.groupId') = id
        AND (claimed_by = ?1 OR EXISTS (SELECT 1 FROM submissions WHERE group_code = ?2))
      AND NOT EXISTS (SELECT 1 FROM revoked_sessions WHERE submission_id = ?1)
    ON CONFLICT(id) DO UPDATE SET data = excluded.data, updated_at = excluded.updated_at WHERE submissions.owner_id = excluded.owner_id`,
  // Klaim atomik: hanya berhasil bila ID masih tersedia (atau sudah milik sesi yang sama) dan sesi belum dihapus.
  claimToken: `UPDATE group_tokens SET status = 'claimed', claimed_by = ?1, data = ?2, updated_at = ?3
    WHERE id = ?4 AND (status IN ('available', 'resubmit_allowed') OR claimed_by = ?1)
      AND NOT EXISTS (SELECT 1 FROM revoked_sessions WHERE submission_id = ?1)`,
  releaseTokenOfDeleted: `UPDATE group_tokens
    SET status = 'available', claimed_by = NULL, updated_at = ?2,
        data = json_set(json_remove(data, '$.claimedAt', '$.claimedBySubmissionId', '$.teamName'), '$.status', 'available')
    WHERE claimed_by = ?1 AND status = 'claimed'
      AND NOT EXISTS (
        SELECT 1 FROM submissions
        WHERE group_code = (SELECT group_code FROM revoked_sessions WHERE submission_id = ?1 LIMIT 1)
      )`,
};

async function isRevoked(db: D1Like, submissionId: string): Promise<boolean> {
  return Boolean(await db.prepare('SELECT 1 AS x FROM revoked_sessions WHERE submission_id = ?').bind(submissionId).first());
}

async function handleGet(request: Request, env: Env, teacherIdentity: string | null): Promise<Response> {
  const db = env.DB;
  const url = new URL(request.url);
  const groupCode = upper(url.searchParams.get('groupCode'));
  const sessionId = url.searchParams.get('sessionId') || '';
  const tokenQuery = teacherIdentity
    ? db.prepare('SELECT data FROM group_tokens WHERE owner_id = ?').bind(teacherIdentity)
    : groupCode
      ? db.prepare('SELECT data FROM group_tokens WHERE code = ?').bind(groupCode)
      : db.prepare('SELECT data FROM group_tokens WHERE 1 = 0');
  const ownerSettingQuery = teacherIdentity
    ? db.prepare('SELECT key, value FROM teacher_app_settings WHERE owner_id = ?').bind(teacherIdentity)
    : groupCode
      ? db.prepare('SELECT key, value FROM teacher_app_settings WHERE owner_id = (SELECT owner_id FROM group_tokens WHERE code = ? LIMIT 1)').bind(groupCode)
      : db.prepare('SELECT key, value FROM teacher_app_settings WHERE 1 = 0');
  const [tokenRows, legacySettingRows, ownerSettingRows, classRows] = await Promise.all([
    tokenQuery.all(),
    db.prepare('SELECT key, value FROM app_settings').all(),
    ownerSettingQuery.all(),
    teacherIdentity
      ? db.prepare('SELECT id FROM classes WHERE teacher_username = ? LIMIT 1').bind(teacherIdentity).all()
      : db.prepare('SELECT id FROM classes LIMIT 1').all(),
  ]);
  // Pengaturan lama menjadi nilai awal/kompatibilitas; pengaturan milik guru akan menimpanya.
  const settings: Record<string, unknown> = {};
  for (const row of legacySettingRows.results) settings[row.key] = parse(row.value);
  for (const row of ownerSettingRows.results) settings[row.key] = parse(row.value);
  const tokens = tokenRows.results.map((r) => parse(r.data)).filter(Boolean);

  if (teacherIdentity) {
    const subs = (await db.prepare('SELECT data FROM submissions WHERE owner_id = ?').bind(teacherIdentity).all()).results.map((r) => parse(r.data)).filter(Boolean);
    return json({ initialized: tokens.length > 0 || subs.length > 0 || legacySettingRows.results.length > 0 || ownerSettingRows.results.length > 0 || classRows.results.length > 0, tokens, submissions: subs, settings });
  }

  const own = groupCode
    ? (await db.prepare('SELECT data FROM submissions WHERE group_code = ?').bind(groupCode).all()).results.map((r) => parse(r.data)).filter(Boolean)
    : [];
  const safeOwn = own.map((s: any) => {
    if (s.status === 'results_published') return s;
    const { evaluation: _e, reviewedAt: _r, publishedAt: _p, ...rest } = s;
    return rest;
  });
  const publicTokens = groupCode ? tokens.filter((d: any) => upper(d.code) === groupCode).map((d: any) => ({ id: d.id, code: d.code, status: d.status, createdAt: d.createdAt })) : [];
  const publicSettings: Record<string, unknown> = {};
  for (const key of PUBLIC_SETTINGS) if (key in settings) publicSettings[key] = settings[key];
  const learningContent = settings.learningContent as any;
  if (learningContent && typeof learningContent === 'object') {
    if (learningContent.published && typeof learningContent.published === 'object') {
      publicSettings.learningContent = learningContent.published;
    } else {
      delete publicSettings.learningContent;
    }
  }
  const body: Record<string, unknown> = {
    initialized: tokens.length > 0 || legacySettingRows.results.length > 0 || ownerSettingRows.results.length > 0 || classRows.results.length > 0,
    tokens: publicTokens, submissions: safeOwn, settings: publicSettings,
  };
  if (sessionId) body.sessionRevoked = await isRevoked(db, sessionId);
  return json(body);
}

async function handlePost(request: Request, env: Env, teacherIdentity: string | null): Promise<Response> {
  const teacher = Boolean(teacherIdentity);
  const db = env.DB;
  let payload: any;
  try { payload = await request.json(); } catch { return json({ error: 'Invalid JSON', code: 'BAD_REQUEST' }, 400); }
  const { upsertTokens = [], deleteTokens = [], upsertSubmissions = [], deleteSubmissions = [], settings = {} } = payload || {};
  if (!isRows(upsertTokens) || !isRows(upsertSubmissions) || !isIds(deleteTokens) || !isIds(deleteSubmissions) ||
      !settings || typeof settings !== 'object' || Array.isArray(settings)) return json({ error: 'Invalid payload', code: 'BAD_REQUEST' }, 400);
  if (upsertTokens.some((t) => typeof t.code !== 'string' || !t.code.trim() || (t.code as string).length > 80)) {
    return json({ error: 'Setiap ID kelompok harus memiliki kode yang valid.', code: 'BAD_REQUEST' }, 400);
  }
  if (Object.keys(settings).some((k) => !SETTINGS_KEYS.has(k))) return json({ error: 'Unsupported settings key', code: 'BAD_REQUEST' }, 400);
  if (!teacher && (deleteTokens.length || deleteSubmissions.length || Object.keys(settings).length)) {
    return json({ error: 'Operasi ini hanya dapat dilakukan oleh guru.', code: 'FORBIDDEN' }, 403);
  }
  const now = Date.now();

  try {
    if (teacher) {
      const batch: D1Stmt[] = [];
      for (const token of upsertTokens as any[]) {
        const code = upper(token.code);
        const data = { ...token, code };
        batch.push(db.prepare(SQL.upsertToken).bind(token.id, code, String(token.status || 'available'), token.claimedBySubmissionId ?? null, JSON.stringify(data), now, teacherIdentity));
        // Sesi yang dicabut guru dicatat permanen agar tidak bisa disimpan lagi oleh perangkat siswa.
        for (const sid of Array.isArray(token.revokedSubmissionIds) ? token.revokedSubmissionIds : []) {
          if (typeof sid === 'string' && sid) batch.push(db.prepare(`INSERT OR IGNORE INTO revoked_sessions (submission_id, group_code, revoked_at)
            SELECT ?, COALESCE((SELECT group_code FROM submissions WHERE id = ? AND owner_id = ?), ?), ?
            WHERE EXISTS (SELECT 1 FROM group_tokens WHERE id = ? AND owner_id = ?)`)
            .bind(sid, sid, teacherIdentity, code, now, token.id, teacherIdentity));
        }
      }
      for (const row of upsertSubmissions as any[]) {
        const rev = await isRevoked(db, row.id);
        if (rev) continue; // guru tidak boleh tanpa sengaja menghidupkan lagi sesi yang sudah dihapus
        batch.push(db.prepare(SQL.upsertSubmissionTeacher).bind(row.id, upper(row.groupCode) || null, JSON.stringify(row), now, teacherIdentity));
      }
      for (const id of deleteSubmissions) {
        batch.push(db.prepare(`INSERT OR IGNORE INTO revoked_sessions (submission_id, group_code, revoked_at)
          SELECT ?, group_code, ? FROM submissions WHERE id = ? AND owner_id = ?`).bind(id, now, id, teacherIdentity));
        batch.push(db.prepare('DELETE FROM submissions WHERE id = ? AND owner_id = ?').bind(id, teacherIdentity));
        batch.push(db.prepare(SQL.releaseTokenOfDeleted.replace("WHERE claimed_by = ?1 AND status = 'claimed'", "WHERE claimed_by = ?1 AND status = 'claimed' AND owner_id = ?3")).bind(id, now, teacherIdentity));
      }
      for (const id of deleteTokens) batch.push(db.prepare('DELETE FROM group_tokens WHERE id = ? AND owner_id = ?').bind(id, teacherIdentity));
      for (const [key, value] of Object.entries(settings as Record<string, unknown>)) {
        // Simpan per guru; JSON null juga disimpan sebagai override agar nilai legacy tidak muncul kembali.
        batch.push(db.prepare(`INSERT INTO teacher_app_settings (owner_id, key, value, updated_at) VALUES (?, ?, ?, ?)
          ON CONFLICT(owner_id, key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at`)
          .bind(teacherIdentity, key, JSON.stringify(value), now));
      }
      if (batch.length) await db.batch(batch);
      return json({ ok: true });
    }

    // ---- siswa: hanya klaim ID kelompok dan simpan sesinya sendiri
    for (const incoming of upsertTokens as any[]) {
      const code = upper(incoming.code);
      if (incoming.status !== 'claimed' || typeof incoming.claimedBySubmissionId !== 'string' || !incoming.claimedBySubmissionId) {
        throw new SyncError('FORBIDDEN', 'Siswa hanya dapat mengklaim ID kelompok.', 403);
      }
      const sid = incoming.claimedBySubmissionId as string;
      const row = await db.prepare('SELECT data, status, claimed_by FROM group_tokens WHERE id = ?').bind(incoming.id).first();
      if (!row) throw new SyncError('TOKEN_MISSING', 'ID kelompok tidak ditemukan.', 409);
      const old = parse(row.data) || {};
      if (upper(old.code) !== code) throw new SyncError('FORBIDDEN', 'Kode ID kelompok tidak boleh diubah oleh siswa.', 403);
      if (row.status === 'disabled') throw new SyncError('FORBIDDEN', 'ID kelompok dinonaktifkan guru.', 403);
      const tokenClassId = typeof old.classId === 'string' ? old.classId : '';
      const tokenClassCode = upper(old.classCode);
      if (tokenClassId && tokenClassCode) {
        const linkedClass = await db.prepare("SELECT id FROM classes WHERE id = ? AND join_code = ? AND status = 'active'")
          .bind(tokenClassId, tokenClassCode).first();
        if (!linkedClass) throw new SyncError('FORBIDDEN', 'Kelas untuk sesi ini tidak aktif atau tidak valid.', 403);
      }
      // Older teacher-issued tokens predate class metadata. Possession of the
      // exact stored token remains the authorization for those existing IDs.
      if (await isRevoked(db, sid)) throw new SyncError('SESSION_DELETED', 'Sesi ini telah dihapus oleh guru. Masukkan kembali ID kelompok untuk memulai sesi baru.', 409);
      const sessionClaim = await db.prepare("SELECT id FROM group_tokens WHERE status = 'claimed' AND claimed_by = ? LIMIT 1").bind(sid).first();
      if (row.status === 'claimed' && row.claimed_by !== sid) {
        const hasGroupSubmission = Boolean(await db.prepare('SELECT 1 AS x FROM submissions WHERE group_code = ? LIMIT 1').bind(code).first());
        if (!hasGroupSubmission || (sessionClaim && sessionClaim.id !== incoming.id)) {
          throw new SyncError('TOKEN_CLAIMED', 'ID kelompok sudah dipakai kelompok lain.', 409);
        }
      }
      // Hanya bidang klaim yang diambil dari siswa; catatan guru dan bidang lain tetap aman.
      const canonicalSubmissionId = row.status === 'claimed' && typeof row.claimed_by === 'string' ? row.claimed_by : sid;
      const merged = {
        ...old, status: 'claimed', claimedBySubmissionId: canonicalSubmissionId,
        claimedAt: old.claimedAt && row.status === 'claimed' ? old.claimedAt : (incoming.claimedAt || new Date(now).toISOString()),
        ...(typeof incoming.teamName === 'string' ? { teamName: incoming.teamName.slice(0, 200) } : {}),
      };
      const res = row.status === 'claimed' && row.claimed_by !== sid
        ? await db.prepare("UPDATE group_tokens SET data = ?, updated_at = ? WHERE id = ? AND code = ? AND status = 'claimed' AND claimed_by = ?")
            .bind(JSON.stringify(merged), now, incoming.id, code, canonicalSubmissionId).run()
        : await db.prepare(SQL.claimToken).bind(sid, JSON.stringify(merged), now, incoming.id).run();
      if (!res.meta?.changes) {
        if (await isRevoked(db, sid)) throw new SyncError('SESSION_DELETED', 'Sesi ini telah dihapus oleh guru. Masukkan kembali ID kelompok untuk memulai sesi baru.', 409);
        throw new SyncError('TOKEN_CLAIMED', 'ID kelompok sudah dipakai kelompok lain.', 409);
      }
    }

    for (const incoming of upsertSubmissions as any[]) {
      const code = upper(incoming.groupCode);
      if (!code) throw new SyncError('FORBIDDEN', 'Jawaban harus terhubung dengan ID kelompok.', 403);
      if (await isRevoked(db, incoming.id)) throw new SyncError('SESSION_DELETED', 'Sesi ini telah dihapus oleh guru. Masukkan kembali ID kelompok untuk memulai sesi baru.', 409);
      const tokenRow = await db.prepare('SELECT id, status, claimed_by FROM group_tokens WHERE code = ?').bind(code).first();
      if (!tokenRow) throw new SyncError('TOKEN_MISSING', 'ID kelompok tidak terdaftar.', 409);
      const hasGroupSubmission = Boolean(await db.prepare('SELECT 1 AS x FROM submissions WHERE group_code = ? LIMIT 1').bind(code).first());
      const sessionClaim = await db.prepare("SELECT id FROM group_tokens WHERE status = 'claimed' AND claimed_by = ? LIMIT 1").bind(incoming.id).first();
      if (tokenRow.status !== 'claimed' || incoming.groupId !== tokenRow.id || (tokenRow.claimed_by !== incoming.id && !hasGroupSubmission) || (sessionClaim && sessionClaim.id !== tokenRow.id)) {
        throw new SyncError('TOKEN_CLAIMED', 'ID kelompok belum diklaim oleh sesi ini.', 409);
      }
      const existingRow = await db.prepare('SELECT group_code, data FROM submissions WHERE id = ?').bind(incoming.id).first();
      const existing = existingRow ? parse(existingRow.data) : null;
      if (existingRow && upper(existingRow.group_code) !== code) throw new SyncError('FORBIDDEN', 'Sesi tidak cocok dengan ID kelompok.', 403);
      if (!STUDENT_STATUSES.has(String(incoming.status))) throw new SyncError('FORBIDDEN', 'Status ini hanya dapat ditetapkan oleh guru.', 403);
      if (existing && ['reviewed', 'results_published'].includes(existing.status)) {
        throw new SyncError('FORBIDDEN', 'Penilaian sudah selesai; minta izin guru untuk mengulang.', 403);
      }
      // Bidang milik guru tidak pernah berasal dari siswa.
      const data = { ...incoming, groupCode: code, evaluation: existing?.evaluation, reviewedAt: existing?.reviewedAt, publishedAt: existing?.publishedAt };
      const res = await db.prepare(SQL.upsertSubmissionStudent).bind(incoming.id, code, JSON.stringify(data), now).run();
      if (!res.meta?.changes) {
        if (await isRevoked(db, incoming.id)) throw new SyncError('SESSION_DELETED', 'Sesi ini telah dihapus oleh guru. Masukkan kembali ID kelompok untuk memulai sesi baru.', 409);
        throw new SyncError('TOKEN_CLAIMED', 'ID kelompok belum diklaim oleh sesi ini.', 409);
      }
    }
    return json({ ok: true });
  } catch (error: any) {
    if (error instanceof SyncError) return json({ error: error.message, code: error.code }, error.status);
    if (/UNIQUE/i.test(String(error?.message))) return json({ error: 'Kode ID kelompok harus unik.', code: 'DUPLICATE_CODE' }, 409);
    console.error('[sync] Database write failed', error);
    return json({ error: 'Data gagal disimpan ke database bersama.', code: 'DB_ERROR' }, 500);
  }
}

export async function handleSync(request: Request, env: Env): Promise<Response> {
  if (request.method === 'OPTIONS') return new Response(null, { status: 204 });
  if (!env.DB) return json({ error: 'Database belum ditautkan. Tambahkan binding D1 bernama DB pada proyek.' }, 503);
  const hasBearer = (request.headers.get('authorization') || '').startsWith('Bearer ');
  const teacherIdentity = await getTeacherIdentity(env, request);
  const teacher = Boolean(teacherIdentity);
  if (hasBearer && !teacher) return json({ error: 'Sesi guru tidak valid atau sudah kedaluwarsa. Silakan login kembali.', code: 'TEACHER_EXPIRED' }, 401);
  try {
    // Data lama tanpa pemilik hanya dapat diadopsi oleh akun bootstrap yang memang dikonfigurasi server.
    if (teacherIdentity && env.TEACHER_USERNAME && teacherIdentity === env.TEACHER_USERNAME) {
      await env.DB.batch([
        env.DB.prepare("UPDATE group_tokens SET owner_id = ? WHERE owner_id = 'legacy'").bind(teacherIdentity),
        env.DB.prepare("UPDATE submissions SET owner_id = ? WHERE owner_id = 'legacy'").bind(teacherIdentity),
      ]);
    }
    if (request.method === 'GET') return await handleGet(request, env, teacherIdentity);
    if (request.method === 'POST') return await handlePost(request, env, teacherIdentity);
    return json({ error: 'Method not allowed' }, 405);
  } catch (error) {
    console.error('[sync] Database error', error);
    return json({ error: 'Database belum tersedia atau skema belum diterapkan (jalankan migrasi D1).' }, 503);
  }
}
